#!/usr/bin/env node
// Writes a standalone workerd config for a `wrangler deploy --dry-run` bundle (see README.md).
// Run it from the directory the config is written to: embed paths are relative to the config.
// Vars: wrangler.jsonc production `vars`, overridable by KITESURF_*/WEB_BOT_AUTH_* env vars.

import { readdirSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const [bundleDir, assetsDir] = process.argv.slice(2).map((p) => p && resolve(p));
if (!bundleDir || !assetsDir) {
  console.error("usage: gen-config.mjs <bundle-dir> <assets-dir>");
  process.exit(2);
}

const wranglerPath = new URL("../../packages/engine/wrangler.jsonc", import.meta.url);
// wrangler.jsonc allows comments and trailing commas; strip both before JSON.parse.
const wrangler = JSON.parse(
  readFileSync(wranglerPath, "utf8")
    .replace(/^\s*\/\/.*$/gm, "")
    .replace(/,(\s*[}\]])/g, "$1"),
);

const vars = { ...wrangler.vars };
for (const [k, v] of Object.entries(process.env)) {
  if (
    (k.startsWith("KITESURF_") || k.startsWith("WEB_BOT_AUTH_")) &&
    k !== "WEB_BOT_AUTH_JWK" &&
    k in vars
  ) {
    vars[k] = v;
  }
}

const capnpString = (s) => JSON.stringify(String(s));

function moduleEntry(file) {
  const path = capnpString(relative(process.cwd(), join(bundleDir, file)));
  const name = capnpString(file);
  if (file === "index.js") return `(name = ${name}, esModule = embed ${path})`;
  if (file.endsWith(".wasm")) return `(name = ${name}, wasm = embed ${path})`;
  // packages/engine/wrangler.jsonc "rules": *.glue.js, *.css, *.dat are Text modules.
  if (/\.(glue\.js|css|dat)$/.test(file)) return `(name = ${name}, text = embed ${path})`;
  return null;
}

const files = readdirSync(bundleDir).sort();
if (!files.includes("index.js")) {
  console.error(`no index.js in ${bundleDir}`);
  process.exit(1);
}
const modules = ["index.js", ...files.filter((f) => f !== "index.js")]
  .map(moduleEntry)
  .filter(Boolean);

const bindings = [
  ...Object.entries(vars).map(([k, v]) => `(name = ${capnpString(k)}, text = ${capnpString(v)})`),
  `(name = "WEB_BOT_AUTH_JWK", fromEnvironment = "WEB_BOT_AUTH_JWK")`,
  `(name = "LOADER", workerLoader = (id = "kitesurf"))`,
  `(name = "FONT_ASSETS", service = "assets")`,
];

const flags = wrangler.compatibility_flags ?? [];

process.stdout.write(`# Generated by deploy/workerd/gen-config.mjs; do not edit.
using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "kitesurf", worker = .engine),
    (name = "assets", disk = (path = ${capnpString(assetsDir)}, writable = false)),
    (name = "internet", network = (allow = ["public"], tlsOptions = (trustBrowserCas = true))),
  ],
  sockets = [
    (name = "http", address = "*:8787", http = (), service = "kitesurf"),
  ],
);

const engine :Workerd.Worker = (
  compatibilityDate = ${capnpString(wrangler.compatibility_date)},
  compatibilityFlags = [${flags.map(capnpString).join(", ")}],
  modules = [
    ${modules.join(",\n    ")},
  ],
  bindings = [
    ${bindings.join(",\n    ")},
  ],
  globalOutbound = "internet",
);
`);
